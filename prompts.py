def build_context(hits) -> str:
    """Единый формат контекста для LLM (hits — список search_engine.Hit)."""
    return "\n".join(
        f"[{n}] ({h.title}, {h.locator or f'фрагмент {h.chunk_index}'}) {h.content}"
        for n, h in enumerate(hits, start=1)
    )